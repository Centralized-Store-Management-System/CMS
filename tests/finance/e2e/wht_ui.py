# ทดสอบหน้าจอ "หนังสือรับรองหัก ณ ที่จ่าย (50 ทวิ)" ในหน้าหลังร้าน: สร้างจากฟอร์มขอเบิก → กรอก → บันทึก + พิมพ์ → แนบกับคำขออัตโนมัติ
# ต้องรีเซ็ต DB (up.sh) + เว็บ python3 -m http.server 8767 ที่โฟลเดอร์ repo
import json
from playwright.sync_api import sync_playwright
exec(open('/tmp/fe2e/flow_ui.py').read().split('\nwith sync_playwright() as p:\n')[0])   # open_ctx, wait_page, post, ok, R, ERR

with sync_playwright() as p:
    b = p.chromium.launch()
    c, pg = open_ctx(p, b, MGR, path='index.html#fin/expflow/new')
    wait_page(pg, 'ขอเบิกค่าใช้จ่าย')
    ok('ฟอร์มขอเบิกมีปุ่ม "บันทึก + สร้างหนังสือหัก ณ ที่จ่าย"', pg.locator('#ffReq [data-save="wht"]').count() == 1)
    pg.fill('#ffReq [name=description]', 'ค่าซ่อมเครื่องชงกาแฟ'); pg.fill('#ffReq [name=amount]', '20000'); pg.fill('#ffReq [name=reference]', 'บริษัท ซ่อมดี จำกัด')
    pg.select_option('#ffReq [name=wht_rate]', '3')
    pg.click('#ffReq [data-save="wht"]'); wait_page(pg, 'สร้างหนังสือรับรองหัก ณ ที่จ่าย')
    ok('บันทึกคำขอแล้วพามาฟอร์ม 50 ทวิ (#fin/wht50/new:…)', pg.evaluate('location.hash').startswith('#fin/wht50/new:'))
    doc = pg.evaluate("location.hash.split(':').pop()")
    v = lambda n: pg.input_value(f'#wtForm [name="{n}"]')
    ok('ผู้จ่ายเงิน = ข้อมูลบริษัท (ชื่อ + เลขผู้เสียภาษี)', v('payer.name') == 'Café Amazon Test' and v('payer.tax_id') == '0105566000001', (v('payer.name'), v('payer.tax_id')))
    ok('ผู้รับเงิน = จ่ายให้ในคำขอ', v('payee.name') == 'บริษัท ซ่อมดี จำกัด')
    ok('รายการเงินได้: ค่าบริการ (ข้อ 5) 20,000 ภาษี 600', pg.input_value('#wtItems [name=code]') == '5' and float(pg.input_value('#wtItems [name=amount]')) == 20000 and float(pg.input_value('#wtItems [name=tax]')) == 600)
    ok('รวมภาษีเป็นตัวอักษร (หกร้อยบาทถ้วน)', 'หกร้อยบาทถ้วน' in pg.inner_text('#wtWords'), pg.inner_text('#wtWords'))
    pg.fill('#wtForm [name="payee.tax_id"]', '0105557083391')
    pg.check('#wtForm [name=form_type][value=pnd53]')
    pg.fill('#wtForm [name="payee.address"]', '145/161 ซอยสุขุมวิท 27 แขวงคลองเตยเหนือ เขตวัฒนา กรุงเทพมหานคร 10110')
    pg.select_option('#wtItems [name=rate]', '5')
    ok('เปลี่ยนอัตราเป็น 5% → ภาษีคำนวณใหม่ 1,000', float(pg.input_value('#wtItems [name=tax]')) == 1000 and 'หนึ่งพันบาทถ้วน' in pg.inner_text('#wtWords'))
    pg.select_option('#wtItems [name=rate]', '3')
    with c.expect_page() as pop:
        pg.click('#wtForm [data-wt="print"]')
    win = pop.value
    win.wait_for_selector('.pg .w', timeout=20000)
    ok('บันทึก + พิมพ์ → เปิดหน้าพิมพ์ 2 ฉบับ (ฉบับที่ 1 / 2) บนหน้าเดียว', win.locator('.pg').count() == 1 and win.locator('.pg .w').count() == 2)
    t = win.inner_text('.pg .w')
    ok('แบบฟอร์มมีหัวข้อตามกรมสรรพากร (มาตรา 50 ทวิ · ผู้มีหน้าที่หัก · ผู้ถูกหัก · คำเตือน)', all(x in t for x in ['หนังสือรับรองการหักภาษี ณ ที่จ่าย', 'มาตรา 50 ทวิ', 'ผู้มีหน้าที่หักภาษี ณ ที่จ่าย', 'ผู้ถูกหักภาษี ณ ที่จ่าย', 'คำเตือน', '3 เตรส']))
    ok('เลขที่ WTI + REF เลขคำขอ + เลข 13 หลักในช่อง', 'WTI-' in t and 'REF#EXP-' in t and win.locator('.pg .w:first-child .d13 i').count() >= 26)
    ok('ติ๊ก ภ.ง.ด.53 + ผู้จ่ายเงิน (1) หัก ณ ที่จ่าย + ฉบับที่ 1', win.evaluate("(()=>{const w=document.querySelector('.pg .w');const on=[...w.querySelectorAll('.cb')].filter(x=>x.textContent.trim()).map(x=>x.parentElement.textContent.trim().slice(0,20));return on.some(s=>s.includes('ภ.ง.ด.53'))&&on.some(s=>s.includes('หัก ณ ที่จ่าย'))&&on.some(s=>s.includes('ฉบับที่ 1'))})()"))
    ok('ยอดลงแถวข้อ 5: 20,000.00 / 600.00 + ตัวอักษร', '20,000' in t and '600' in t and 'หกร้อยบาทถ้วน' in t)
    win.set_viewport_size({'width': 1240, 'height': 900}); win.screenshot(path='/tmp/fe2e/wht-print.png', full_page=True)
    win.emulate_media(media='print')
    ok('หน้าพิมพ์: แถบปุ่มซ่อนตอนพิมพ์', not win.locator('.bar').is_visible())
    win.close()
    wait_page(pg, 'ค่าซ่อมเครื่องชงกาแฟ')
    ok('กลับหน้าคำขอ → 50 ทวิ แนบอยู่ในคำขอ (เลขที่ + ปุ่มพิมพ์)', pg.locator('#ffWht [data-wht-print]').count() == 1 and 'WTI-' in pg.inner_text('#ffWht'), pg.inner_text('#ffWht') if pg.locator('#ffWht').count() else '')
    with c.expect_page() as pop2:
        pg.click('#ffWht [data-wht-print]')
    w2 = pop2.value; w2.wait_for_selector('.pg .w', timeout=20000)
    ok('กดพิมพ์จากหน้าคำขอ → เปิดฉบับเดิม', 'บริษัท ซ่อมดี จำกัด' in w2.inner_text('.pg')); w2.close()
    pg.click('#ffWht [data-go^="#wht50/edit:"]'); wait_page(pg, 'แก้ไข WTI-')
    pg.fill('#wtForm [name=book_no]', '7'); pg.click('#wtForm [data-wt="save"]'); wait_page(pg, 'ค่าซ่อมเครื่องชงกาแฟ')
    pg.click('#ffWht [data-go^="#wht50/"]:not([data-go*=":"])'); wait_page(pg, 'WTI-')
    pg.wait_for_function("(()=>{const f=document.querySelector('.wt-frame');return f&&f.contentDocument&&f.contentDocument.querySelector('.w')})()", timeout=15000)
    ok('หน้าดูหนังสือ: ตัวอย่างแบบฟอร์ม + เล่มที่ที่แก้แล้ว', '7' in pg.evaluate("document.querySelector('.wt-frame').contentDocument.querySelector('.no').textContent"))
    pg.click('#fmContent [data-go^="#expflow/"]'); wait_page(pg, 'ค่าซ่อมเครื่องชงกาแฟ')
    pg.click('#ffWht [data-wht-void]'); answer(pg, 'ทดสอบยกเลิก')
    pg.wait_for_function("document.querySelector('#ffWht .ff-void')", timeout=15000)
    ok('ยกเลิกหนังสือ → แสดงว่ายกเลิกแล้ว ไม่มีปุ่มพิมพ์', pg.locator('#ffWht [data-wht-print]').count() == 0 and 'ยกเลิกแล้ว' in pg.inner_text('#ffWht'))
    c.close()
    # มือถือ: ฟอร์มไม่ล้นจอ
    c, pg = open_ctx(p, b, MGR, mobile=True, path='index.html#fin/wht50/new:' + doc)
    wait_page(pg, 'สร้างหนังสือรับรองหัก ณ ที่จ่าย')
    over = pg.evaluate("document.documentElement.scrollWidth - innerWidth")
    ok('มือถือ: ฟอร์ม 50 ทวิ ไม่ล้นจอ', over <= 1, over)
    pg.screenshot(path='/tmp/fe2e/wht-mobile.png', full_page=True)
    c.close()
    # ผู้ตรวจสุดท้าย: ดูได้ ไม่มีปุ่มสร้าง
    c, pg = open_ctx(p, b, VER, path='index.html#fin/expflow/' + doc)
    wait_page(pg, 'ค่าซ่อมเครื่องชงกาแฟ')
    ok('ผู้ตรวจสุดท้าย: เห็นรายการ 50 ทวิ แต่ไม่มีปุ่มสร้าง/ยกเลิก', pg.locator('#ffWht').count() == 1 and pg.locator('#ffWht [data-go^="#wht50/new:"]').count() == 0 and pg.locator('#ffWht [data-wht-void]').count() == 0)
    c.close()
    b.close()
print('errors', [e for e in ERR if 'net::' not in e])
print(f'ผ่าน {sum(R)} / {len(R)}')
